        Image(
            painter = painterResource(id = R.drawable.img_sanctum_hero),
            contentDescription = "Gothic Cathedral Abyss",
            contentScale = ContentScale.Crop,
            alpha = 0.52f,
            modifier = Modifier.fillMaxSize()
        )

        Box(
            modifier = Modifier
                .fillMaxSize()
                .background(
                    Brush.verticalGradient(
                        colors = listOf(
                            AbyssalObsidian.copy(alpha = 0.45f),
                            AbyssalObsidian.copy(alpha = 0.78f),
                            AbyssalObsidian
                        )
                    )
                )
        )

        Column(
            modifier = Modifier
                .fillMaxSize()
                .windowInsetsPadding(WindowInsets.safeDrawing)
                .padding(horizontal = 24.dp, vertical = 20.dp)
                .widthIn(max = 520.dp)
                .align(Alignment.Center),
            horizontalAlignment = Alignment.CenterHorizontally,
            verticalArrangement = Arrangement.SpaceBetween
        ) {
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.End,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Icon(
                    imageVector = Icons.Default.Language,
                    contentDescription = "Language",
                    tint = EmberGold,
                    modifier = Modifier.size(18.dp).padding(end = 4.dp)
                )
                FilterChip(
                    selected = currentLanguage == AppLanguage.INDONESIAN,
                    onClick = { onLanguageSelected(AppLanguage.INDONESIAN) },
                    label = { Text("ID") },
                    colors = FilterChipDefaults.filterChipColors(
                        selectedContainerColor = EmberGold,
                        selectedLabelColor = AbyssalObsidian
                    ),
                    modifier = Modifier.padding(end = 6.dp).testTag("lang_id_chip")
                )
                FilterChip(
                    selected = currentLanguage == AppLanguage.ENGLISH,
                    onClick = { onLanguageSelected(AppLanguage.ENGLISH) },
                    label = { Text("EN") },
                    colors = FilterChipDefaults.filterChipColors(
                        selectedContainerColor = EmberGold,
                        selectedLabelColor = AbyssalObsidian
                    ),
                    modifier = Modifier.testTag("lang_en_chip")
                )
            }

            Column(
                horizontalAlignment = Alignment.CenterHorizontally,
                modifier = Modifier.padding(vertical = 24.dp)
            ) {
                Icon(
                    imageVector = Icons.Default.Shield,
                    contentDescription = "Nocturne Emblem",
                    tint = EmberGold,
                    modifier = Modifier.size(56.dp)
                )
                Spacer(modifier = Modifier.height(16.dp))
                Text(
                    text = strings.appTitle,
                    style = MaterialTheme.typography.displayLarge,
                    color = EmberGold,
                    textAlign = TextAlign.Center
                )
                Spacer(modifier = Modifier.height(8.dp))
                Text(
                    text = strings.subtitle,
                    style = MaterialTheme.typography.titleMedium,
                    color = MaterialTheme.colorScheme.onBackground,
                    textAlign = TextAlign.Center
                )
            }

            Surface(
                color = CryptSlate.copy(alpha = 0.92f),
                shape = RoundedCornerShape(16.dp),
                border = BorderStroke(1.dp, CarvedStoneBorder),
